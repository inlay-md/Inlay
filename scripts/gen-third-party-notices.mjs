// Generates THIRD_PARTY_NOTICES.md from shipped npm dependencies, Swift packages and
// bundled fonts. `--check` fails when the committed file is stale (run `pnpm notices`).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { licenseText, npmPackages, readJson, repoRoot, swiftPins } from './lib/deps.mjs';

const check = process.argv.includes('--check');
const outPath = join(repoRoot, 'THIRD_PARTY_NOTICES.md');

const swift = readJson('scripts/swift-packages.json').packages;
const fonts = readJson('scripts/bundled-fonts.json').fonts;
const npm = npmPackages({ prod: true });

const lines = [
  '# Third-party notices',
  '',
  'Inlay bundles the following third-party software and fonts. Each is used under its own license, reproduced or referenced below. This file is generated by `scripts/gen-third-party-notices.mjs`; do not edit by hand.',
  '',
  `Inlay itself is licensed under the Apache License 2.0 (see LICENSE). Summary: ${npm.length} npm packages, ${swift.length} Swift packages, ${fonts.length} font families.`,
  '',
];

lines.push('## npm packages', '');
if (npm.length === 0) lines.push('_No shipped npm dependencies yet._', '');
for (const p of npm) {
  lines.push(`### ${p.name} ${p.versions.join(', ')}`, '');
  lines.push(`- License: ${p.license}`);
  if (p.homepage) lines.push(`- Homepage: ${p.homepage}`);
  if (p.author) lines.push(`- Author: ${p.author}`);
  lines.push('');
  const text = licenseText(p.paths[0]);
  if (text) lines.push('```text', text, '```', '');
  else lines.push('_License text not found in the package; see the homepage._', '');
}

lines.push('## Swift packages', '');
const pins = swiftPins();
if (pins.length === 0) lines.push('_No Swift package dependencies yet._', '');
for (const pin of pins) {
  const entry = swift.find((s) => s.identity.toLowerCase() === pin.identity.toLowerCase());
  lines.push(`### ${pin.identity} ${pin.version ?? ''}`.trim(), '');
  lines.push(`- License: ${entry?.license ?? 'UNKNOWN'}`, `- Source: ${pin.url}`, '');
  if (entry?.licenseFile) {
    try {
      lines.push(
        '```text',
        readFileSync(join(repoRoot, entry.licenseFile), 'utf8').trim(),
        '```',
        '',
      );
    } catch {
      lines.push('_License file missing._', '');
    }
  }
}

lines.push('## Fonts', '');
if (fonts.length === 0) lines.push('_No bundled fonts yet (system fonts are used)._', '');
for (const f of fonts) {
  lines.push(`### ${f.name}`, '', `- License: ${f.license}`, `- Source: ${f.source}`, '');
}

const content = `${lines.join('\n').trimEnd()}\n`;
if (check) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== content) {
    console.error('THIRD_PARTY_NOTICES.md is stale. Run `pnpm notices` and commit the result.');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date.');
} else {
  writeFileSync(outPath, content);
  console.log(
    `Wrote THIRD_PARTY_NOTICES.md (${npm.length} npm, ${pins.length} Swift, ${fonts.length} fonts).`,
  );
}
