// Deterministically (re)generates the binary-ish fixtures that cannot be
// authored safely by hand: mixed line endings, BOM, undecodable bytes and the
// 10k-line performance file. Run: node fixtures/scripts/generate.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'md');
const enc = new TextEncoder();

// --- mixed-line-endings.md: CRLF majority, a few LF, one lone CR ---
{
  const lines = [
    '# Mixed line endings',
    '',
    'Most lines end with CRLF.',
    'This one ends with a bare LF.',
    'Back to CRLF.',
    '',
    '- list item one',
    '- list item two',
    '',
    'A lone CR follows this line.',
    'Then CRLF again.',
    '',
    '```',
    'code block line 1',
    'code block line 2',
    '```',
    '',
    'Last line.',
  ];
  const eols = ['\r\n', '\r\n', '\r\n', '\n', '\r\n', '\r\n', '\r\n', '\r\n', '\n', '\r', '\r\n', '\r\n', '\r\n', '\r\n', '\r\n', '\r\n', '\r\n', '\r\n'];
  const text = lines.map((l, i) => l + eols[i]).join('');
  writeFileSync(join(out, 'mixed-line-endings.md'), enc.encode(text));
}

// --- crlf.md: uniform CRLF ---
{
  const text = ['# CRLF file', '', 'Every line ends with CRLF, including the last.', '', '| a | b |', '|---|---|', '| 1 | 2 |', ''].join('\r\n');
  writeFileSync(join(out, 'crlf.md'), enc.encode(text));
}

// --- utf8-bom.md ---
{
  const text = '# UTF-8 BOM\n\nThis file starts with a byte order mark (EF BB BF) that must be preserved.\n';
  writeFileSync(join(out, 'utf8-bom.md'), Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(enc.encode(text))]));
}

// --- undecodable.md: invalid UTF-8 in the middle ---
{
  const head = enc.encode('# Undecodable\n\nValid text, then invalid bytes: ');
  const bad = Buffer.from([0xff, 0xfe, 0xc3, 0x28, 0xa0, 0xa1]);
  const tail = enc.encode(' and valid text again.\n');
  writeFileSync(join(out, 'undecodable.md'), Buffer.concat([Buffer.from(head), bad, Buffer.from(tail)]));
}

// --- perf-10k-lines.md: >10k lines of varied markdown, seeded PRNG ---
{
  let seed = 20261105;
  const rnd = () => {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    return seed / 2 ** 32;
  };
  const pick = (arr) => arr[Math.floor(rnd() * arr.length)];
  const words = 'markdown render editor island source byte sacred svg html chart widget inlay webkit remark table list code quick look fixture performance Việt 中文 emoji 🙂'.split(' ');
  const sentence = (n) => Array.from({ length: n }, () => pick(words)).join(' ');
  const lines = ['# Performance fixture (generated)', '', 'Generated by fixtures/scripts/generate.mjs with a fixed seed. Do not edit by hand.', ''];
  let section = 0;
  while (lines.length < 10_200) {
    section++;
    lines.push(`## Section ${section}: ${sentence(3)}`, '');
    const kind = Math.floor(rnd() * 6);
    if (kind === 0) {
      for (let i = 0; i < 6; i++) lines.push(`${sentence(12)} **${pick(words)}** and *${pick(words)}* with \`${pick(words)}\`.`);
      lines.push('');
    } else if (kind === 1) {
      for (let i = 0; i < 8; i++) lines.push(`- ${sentence(5)}`);
      lines.push('');
    } else if (kind === 2) {
      lines.push('```js');
      for (let i = 0; i < 10; i++) lines.push(`const ${pick(words).replace(/[^a-z]/gi, '') || 'x'}${i} = ${i} * ${Math.floor(rnd() * 100)}; // ${sentence(3)}`);
      lines.push('```', '');
    } else if (kind === 3) {
      lines.push('| Name | Value | Notes |', '|---|---:|:---:|');
      for (let i = 0; i < 6; i++) lines.push(`| ${pick(words)} | ${Math.floor(rnd() * 1000)} | ${sentence(3)} |`);
      lines.push('');
    } else if (kind === 4) {
      for (let i = 0; i < 5; i++) lines.push(`${i + 1}. ${sentence(6)}`);
      lines.push('');
    } else {
      lines.push(`> ${sentence(10)}`, `> ${sentence(8)}`, '', `$$`, `\\sum_{i=0}^{${section}} x_i^2`, `$$`, '');
    }
  }
  writeFileSync(join(out, 'perf-10k-lines.md'), enc.encode(lines.join('\n') + '\n'));
}
console.log('fixtures generated');
